/**
 * Converts text offline between supported scripts and languages
 */
export function offlineTransliterate(text: string, targetLang: LanguageCode): string {
  if (!text) return '';

  if (targetLang === 'pa') {
    // Convert to Gurmukhi (Punjabi)
    return text.split('').map(char => DEVANAGARI_TO_GURMUKHI_MAP[char] || char).join('');
  }

  if (targetLang === 'ur') {
    // Convert to Urdu script
    return text.split('').map(char => DEVANAGARI_TO_URDU_MAP[char] || char).join('');
  }

  if (targetLang === 'sa') {
    // Add classical Sanskrit suffixes or anusvara endings where appropriate
    return text
      .replace(/प्रश्न/g, 'प्रश्नाः')
      .replace(/उत्तर/g, 'उत्तरम्')
      .replace(/विकल्प/g, 'विकल्पाः')
      .replace(/परीक्ष/g, 'परीक्षा');
  }

  return text;
}
